package io.quarkiverse.amazon.codegen.docs;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Objects;

import io.quarkiverse.amazon.codegen.model.QuarkusServiceModel;
import software.amazon.awssdk.codegen.model.intermediate.Metadata;

/**
 * Writes the AsciiDoc attributes of the documentation page of a service, {@code <docsPageName>.adoc}, in the
 * {@code _metadata} directory of the documentation.
 * <p>
 * Every value is taken as is from the service model, the Quarkus customization or the module layout.
 */
public class DocsMetadataGenerator {

    static final String HEADER = "// Generated by quarkus-amazon-codegen-maven-plugin, do not edit.";

    private final QuarkusServiceModel model;
    private final String extensionName;

    public DocsMetadataGenerator(QuarkusServiceModel model, String extensionName) {
        this.model = model;
        this.extensionName = extensionName;
    }

    /**
     * @return the content of the metadata file
     */
    public String content() {
        Metadata metadata = model.intermediateModel().getMetadata();
        String serviceName = model.configName();
        String extension = extensionName != null ? extensionName : serviceName;

        List<String> lines = new ArrayList<>();
        lines.add(HEADER);
        lines.add(attribute("service-name", serviceName));
        lines.add(attribute("service-name-uppercase", model.displayName()));
        lines.add(attribute("service-class-name", metadata.getServiceName()));
        if (!Objects.equals(extension, serviceName)) {
            lines.add(attribute("extension-name", extension));
        }
        if (!Objects.equals(metadata.getClientPackageName(), extension)) {
            lines.add(attribute("sdk-package", metadata.getClientPackageName()));
        }
        if (!Objects.equals(model.packageName(), extension)) {
            lines.add(attribute("java-package", model.packageName()));
        }
        return String.join("\n", lines) + "\n";
    }

    /**
     * Writes {@code <docsPageName>.adoc} in the given directory, only if its content changed.
     *
     * @return the written file
     */
    public Path write(Path directory) {
        Path file = directory.resolve(model.docsPageName() + ".adoc");
        String content = content();
        try {
            if (Files.exists(file) && Files.readString(file, StandardCharsets.UTF_8).equals(content)) {
                return file;
            }
            Files.createDirectories(directory);
            Files.writeString(file, content, StandardCharsets.UTF_8);
            return file;
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to write " + file, e);
        }
    }

    private static String attribute(String name, String value) {
        return ":" + name + ": " + value;
    }
}
