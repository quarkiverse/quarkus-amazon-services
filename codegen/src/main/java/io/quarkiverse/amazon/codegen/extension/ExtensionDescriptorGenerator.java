package io.quarkiverse.amazon.codegen.extension;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

import io.quarkiverse.amazon.codegen.model.QuarkusServiceModel;

/**
 * Writes the Quarkus extension descriptor of the runtime module, {@code META-INF/quarkus-extension.yaml}, in the
 * generated resources directory.
 * <p>
 * The {@code ${project.*}} placeholders are resolved by the {@code extension-descriptor} goal of the
 * {@code quarkus-extension-maven-plugin}.
 */
public class ExtensionDescriptorGenerator {

    static final String HEADER = "# Generated by quarkus-amazon-codegen-maven-plugin, do not edit.";

    static final String GUIDE_BASE_URL = "https://docs.quarkiverse.io/quarkus-amazon-services/dev/";

    private final QuarkusServiceModel model;
    private final String extensionName;

    public ExtensionDescriptorGenerator(QuarkusServiceModel model, String extensionName) {
        this.model = model;
        this.extensionName = extensionName;
    }

    /**
     * @return the content of the extension descriptor
     */
    public String content() {
        List<String> keywords = new ArrayList<>();
        keywords.add(extensionName != null ? extensionName : model.configName());
        keywords.addAll(model.keywords());
        keywords.add("aws");
        keywords.add("amazon");

        List<String> lines = new ArrayList<>();
        lines.add(HEADER);
        lines.add("---");
        lines.add("artifact: ${project.groupId}:${project.artifactId}:${project.version}");
        lines.add("name: " + quote(model.displayName()));
        lines.add("metadata:");
        lines.add("  keywords:");
        keywords.forEach(k -> lines.add("    - " + quote(k)));
        lines.add("  categories:");
        model.categories().forEach(c -> lines.add("    - " + quote(c)));
        lines.add("  guide: " + GUIDE_BASE_URL + model.docsPageName() + ".html");
        lines.add("  status: " + quote(model.status()));
        lines.add("  config:");
        lines.add("  - " + quote(model.configPrefix() + "."));
        return String.join("\n", lines) + "\n";
    }

    /**
     * Writes {@code META-INF/quarkus-extension.yaml} in the given resources directory, only if its content changed.
     *
     * @return the written file
     */
    public Path write(Path resourcesDirectory) {
        Path file = resourcesDirectory.resolve("META-INF").resolve("quarkus-extension.yaml");
        String content = content();
        try {
            if (Files.exists(file) && Files.readString(file, StandardCharsets.UTF_8).equals(content)) {
                return file;
            }
            Files.createDirectories(file.getParent());
            Files.writeString(file, content, StandardCharsets.UTF_8);
            return file;
        } catch (IOException e) {
            throw new UncheckedIOException("Failed to write " + file, e);
        }
    }

    private static String quote(String value) {
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
